// Bundle the web prototype: web/src/main.ts (+ ../../core) -> web/game.js
// Run: npm run build:web
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

// Art decision (2026-10-27, by gami): do NOT ship sprites sliced from the
// reference boards — they are study material only. gami will supply an
// original art pass later; until then the game renders with its own
// procedural placeholder art, so SPRITES stays empty on purpose.
// (web/assets/ + tools/slice_assets.py remain in the workspace as the
// slicing study, they are simply not bundled.)
writeFileSync(
  "web/src/sprites.ts",
  "// generated by web/build.mjs — intentionally empty (see build.mjs note)\nexport const SPRITES: Record<string, string> = {};\n",
);
console.log("sprites.ts generated: empty (original art pending)");

await build({
  entryPoints: ["web/src/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  outfile: "web/game.js",
  sourcemap: false,
  logLevel: "info",
});
console.log("web/game.js built");

// Standalone single-file build: inline the bundle into index.html so the
// game survives being shared as ONE file (chat attachments, file previews
// that drop sibling files). Output: web/xap-standalone.html
const js = readFileSync("web/game.js", "utf8");
if (js.includes("</script>")) throw new Error("bundle contains </script>, cannot inline safely");
const html = readFileSync("web/index.html", "utf8");
const tag = '<script src="game.js"></script>';
if (!html.includes(tag)) throw new Error("script tag not found in index.html");
writeFileSync("web/xap-standalone.html", html.replace(tag, "<script>\n" + js + "\n</script>"));
console.log("web/xap-standalone.html built");
