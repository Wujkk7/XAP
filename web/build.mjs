// Bundle the web prototype and the shared Cocos core -> web/game.js
// Run: npm run build:web
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

// Generate web/src/sprites.ts from the shared Cocos PNGs so the
// standalone build stays a single self-contained file. The PNGs are sliced by
// tools/slice_assets_v2.py from gami's OWN v2 art boards
// (assets/reference/v2/) — this is the art set the game ships with.
const artDirectory = "cocos/assets/resources/art";
const assetFiles = readdirSync(artDirectory).filter((f) => f.endsWith(".png")).sort();
const entries = assetFiles
  .map((f) => "  " + JSON.stringify(f.replace(/\.png$/, "")) + ": \"data:image/png;base64," + readFileSync(artDirectory + "/" + f).toString("base64") + "\",")
  .join("\n");
writeFileSync(
  "web/src/sprites.ts",
  "// generated by web/build.mjs from cocos/assets/resources/art/*.png — do not edit\nexport const SPRITES: Record<string, string> = {\n" + entries + "\n};\n",
);
console.log("sprites.ts generated:", assetFiles.length, "sprites");

await build({
  entryPoints: ["web/src/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  outfile: "web/game.js",
  sourcemap: false,
  logLevel: "info",
});
console.log("web/game.js built");

// Standalone single-file build: inline the bundle into index.html so the
// game survives being shared as ONE file (chat attachments, file previews
// that drop sibling files). Output: web/xap-standalone.html
const js = readFileSync("web/game.js", "utf8");
if (js.includes("</script>")) throw new Error("bundle contains </script>, cannot inline safely");
const html = readFileSync("web/index.html", "utf8");
const tag = '<script src="game.js"></script>';
if (!html.includes(tag)) throw new Error("script tag not found in index.html");
writeFileSync("web/xap-standalone.html", html.replace(tag, "<script>\n" + js + "\n</script>"));
console.log("web/xap-standalone.html built");
